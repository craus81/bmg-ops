CREATE TEMP TABLE _new_kits ON COMMIT DROP AS
SELECT k.* FROM _prime_kits k
 WHERE NOT EXISTS (SELECT 1 FROM part_kits pk WHERE upper(pk.item_number) = upper(k.item_number));

INSERT INTO part_kits (name, description, item_number, vendor, short_description, active)
SELECT n.name, n.short_description, n.item_number, 'Prime Design', n.short_description, true
  FROM _new_kits n;

INSERT INTO part_kit_items (kit_id, part_id, item_number, description, quantity, sort_order)
SELECT pk.id,
       (SELECT p.id FROM netsuite_parts p
         WHERE upper(p.item_number) = upper(i.item_number) AND p.is_active
         ORDER BY p.last_synced_at DESC NULLS LAST LIMIT 1),
       i.item_number, i.description, i.quantity, i.sort_order
  FROM _prime_kit_items i
  JOIN _new_kits n ON n.item_number = i.kit_item_number
  JOIN part_kits pk ON upper(pk.item_number) = upper(i.kit_item_number);
