-- Migration 453: in-app Requests (Craig, 2026-10-30, thread "Build in-app
-- bug and feature requests").
--
-- Anyone signed in to FleetSuite reports a problem, asks for a feature or
-- asks a question from More → Requests (or the card on Home). Claude picks
-- new ones up on a schedule through /api/requests/agent (a token, not a
-- session), works them, and writes the answer back under the request. Code
-- still waits for Craig's "Ship it", so a request can sit at Waiting on
-- Craig. Only Craig closes one as Won't do, with a reason the person sees.
--
-- Staff see every request (cuts down on duplicates, and "Me too" backs one
-- up); customer and installer accounts see only their own, and their alerts
-- stay in the app (no email to customers).
--
-- No RLS policies: service role only, behind the /api/requests routes.

CREATE TABLE IF NOT EXISTS app_requests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- "#12" on screen and in alerts.
  number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  kind TEXT NOT NULL CHECK (kind IN ('problem', 'idea', 'question')),
  body TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'looking', 'waiting', 'done', 'wont')),
  -- The screen the person came from ("/admin/scans") and their device, so
  -- they don't have to explain where the problem is.
  from_page TEXT,
  device TEXT,
  created_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
  -- True while Claude owes a look: a new request, or a person replied.
  needs_claude BOOLEAN NOT NULL DEFAULT true,
  -- The red dot on the submitter's list row: someone answered them.
  submitter_unread BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS app_requests_updated_idx ON app_requests (updated_at DESC, id);
CREATE INDEX IF NOT EXISTS app_requests_needs_claude_idx ON app_requests (created_at) WHERE needs_claude;
CREATE INDEX IF NOT EXISTS app_requests_created_by_idx ON app_requests (created_by);

ALTER TABLE app_requests ENABLE ROW LEVEL SECURITY;

-- The conversation under a request: people (submitter, Craig, anyone who
-- can see it) and Claude.
CREATE TABLE IF NOT EXISTS app_request_messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id UUID NOT NULL REFERENCES app_requests(id) ON DELETE CASCADE,
  author_kind TEXT NOT NULL CHECK (author_kind IN ('person', 'claude')),
  author_id UUID REFERENCES profiles(id) ON DELETE SET NULL,
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS app_request_messages_request_idx ON app_request_messages (request_id, created_at);

ALTER TABLE app_request_messages ENABLE ROW LEVEL SECURITY;

-- Screenshots, stored under the app-requests/ prefix (denied to the generic
-- storage API; served only by /api/requests/files and the agent route).
CREATE TABLE IF NOT EXISTS app_request_files (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id UUID NOT NULL REFERENCES app_requests(id) ON DELETE CASCADE,
  storage_path TEXT NOT NULL,
  file_name TEXT,
  content_type TEXT,
  created_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS app_request_files_request_idx ON app_request_files (request_id, created_at);

ALTER TABLE app_request_files ENABLE ROW LEVEL SECURITY;

-- "Me too": other people backing up a request instead of sending it again.
CREATE TABLE IF NOT EXISTS app_request_me_too (
  request_id UUID NOT NULL REFERENCES app_requests(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (request_id, user_id)
);

ALTER TABLE app_request_me_too ENABLE ROW LEVEL SECURITY;
