/** Miles from the shop for a ZIP (5 digits, or ZIP+4), or null when outside the area. */
export function areaMiles(zip: string | null | undefined): number | null {
  const z = String(zip || '').trim().slice(0, 5);
  const m = AREA_ZIP_MILES.get(z);
  return m == null ? null : m;
}
